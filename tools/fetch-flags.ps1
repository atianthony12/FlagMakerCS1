# Fetches the world's flags as images -- every country and territory of ISO 3166-1 that
# Flagpedia serves, England, Scotland, Wales, Northern Ireland, the EU and the UN (not the US
# states) -- from flagcdn.com, Flagpedia.net's CDN, and writes:
#
#   RealFlag\Resources\Flags\<image>.png         640 px wide, the flag's own proportions
#   RealFlag\Resources\Flags\Small\<image>.png   80 px wide, the country picker's thumbnail
#   RealFlag\Flags\FlagCountries.cs              the table: code, English name, proportion, image
#
# Flagpedia's terms: "The flag images provided on our website are in the public domain and can
# be used freely without restriction" (flagpedia.net/terms); they are drawn from Wikimedia
# Commons' vector files. Credited in LICENSE and README.md all the same.
#
# A flag two codes share (Norway's for Svalbard and Bouvet Island, say) is stored once: the
# table points both codes at one image. The proportion (height / length x 1000, what
# FlagSpec.Proportion holds) is read from the 640 px image's own size, which Flagpedia draws
# at each flag's official proportions (the United States 10:19, Qatar 11:28, Nepal taller than
# long).
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\fetch-flags.ps1
#
# Run it again to bring the flags up to date; the build embeds whatever is in the folder.

param(
    [int]$Width = 640,
    [int]$SmallWidth = 80
)

$ErrorActionPreference = "Stop"
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
$root = Resolve-Path (Join-Path $PSScriptRoot "..")
$flagsDir = Join-Path $root "RealFlag\Resources\Flags"
$smallDir = Join-Path $flagsDir "Small"
$table = Join-Path $root "RealFlag\Flags\FlagCountries.cs"
New-Item -ItemType Directory -Force $flagsDir, $smallDir | Out-Null

$web = New-Object Net.WebClient
$web.Headers.Add("User-Agent", "RealFlag fetch-flags.ps1")
$utf8 = New-Object Text.UTF8Encoding($false)

$codesJson = $utf8.GetString($web.DownloadData("https://flagcdn.com/en/codes.json"))
$codes = $codesJson | ConvertFrom-Json
$entries = @()
foreach ($p in $codes.PSObject.Properties) {
    if ($p.Name -like "us-*") { continue }
    $entries += [pscustomobject]@{ Code = $p.Name; Name = $p.Value }
}
"$($entries.Count) codes (the US states left out)"

function Size([byte[]]$png) {
    # IHDR: width and height, big-endian, at bytes 16 and 20.
    $w = ([int]$png[16] -shl 24) -bor ([int]$png[17] -shl 16) -bor ([int]$png[18] -shl 8) -bor [int]$png[19]
    $h = ([int]$png[20] -shl 24) -bor ([int]$png[21] -shl 16) -bor ([int]$png[22] -shl 8) -bor [int]$png[23]
    return @($w, $h)
}

$sha = [Security.Cryptography.SHA1]::Create()
$fetched = @()
foreach ($e in $entries) {
    $big = $web.DownloadData("https://flagcdn.com/w$Width/$($e.Code).png")
    $small = $web.DownloadData("https://flagcdn.com/w$SmallWidth/$($e.Code).png")
    $size = Size $big
    if ($size[0] -ne $Width) { throw "$($e.Code): $($size[0]) px wide, not $Width" }
    $fetched += [pscustomobject]@{ Code = $e.Code; Name = $e.Name; Big = $big; Small = $small; Size = $size;
                                   Hash = [BitConverter]::ToString($sha.ComputeHash($big)) }
}

# One image per distinct flag, named after the code with the shortest name among those that
# share it: the country's own, not its territories' (Norway, not Bouvet Island).
$imageOf = @{}
foreach ($group in ($fetched | Group-Object Hash)) {
    $owner = $group.Group | Sort-Object { $_.Name.Length }, Code | Select-Object -First 1
    foreach ($f in $group.Group) { $imageOf[$f.Code] = $owner.Code }
}

$rows = @()
$stored = 0; $bytes = 0
foreach ($f in $fetched) {
    $image = $imageOf[$f.Code]
    if ($image -eq $f.Code) {
        [IO.File]::WriteAllBytes((Join-Path $flagsDir "$image.png"), $f.Big)
        [IO.File]::WriteAllBytes((Join-Path $smallDir "$image.png"), $f.Small)
        $stored++; $bytes += $f.Big.Length + $f.Small.Length
    }

    $proportion = [int][Math]::Round(1000.0 * $f.Size[1] / $f.Size[0])
    $rows += [pscustomobject]@{ Code = $f.Code; Name = $f.Name; Proportion = $proportion; Image = $image }
}

# A stale image (a code Flagpedia dropped) must not linger in the build.
$keep = @{}; foreach ($r in $rows) { $keep[$r.Image] = $true }
foreach ($dir in $flagsDir, $smallDir) {
    foreach ($f in Get-ChildItem $dir -Filter "*.png") {
        if (-not $keep.ContainsKey($f.BaseName)) { Remove-Item $f.FullName -Force }
    }
}

# ---- the table ------------------------------------------------------------------------------

$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine("// GENERATED by tools\fetch-flags.ps1 from flagcdn.com's codes.json and images (Flagpedia.net:")
[void]$sb.AppendLine("// public domain, after Wikimedia Commons). Do not edit: run the script again.")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("namespace RealFlag.Flags")
[void]$sb.AppendLine("{")
[void]$sb.AppendLine("    public static partial class FlagCountries")
[void]$sb.AppendLine("    {")
[void]$sb.AppendLine("        /// <summary>Every flag: its code (ISO 3166-1, lower case; gb-eng, eu, un...), English name, proportion (height / length x 1000) and image.</summary>")
[void]$sb.AppendLine("        private static readonly FlagCountry[] Table =")
[void]$sb.AppendLine("        {")
foreach ($r in $rows) {
    $name = $r.Name.Replace("\", "\\").Replace('"', '\"')
    [void]$sb.AppendLine(('            new FlagCountry("{0}", "{1}", {2}, "{3}"),' -f $r.Code, $name, $r.Proportion, $r.Image))
}
[void]$sb.AppendLine("        };")
[void]$sb.AppendLine("    }")
[void]$sb.AppendLine("}")
[IO.File]::WriteAllText($table, $sb.ToString(), (New-Object Text.UTF8Encoding($true)))

"$($rows.Count) flags, $stored images stored ($([int]($bytes / 1024)) KB with the thumbnails), $($rows.Count - $stored) codes sharing another's"
"wrote $table"

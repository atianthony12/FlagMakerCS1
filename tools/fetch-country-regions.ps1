# Writes RealFlag\Flags\FlagRegions.cs: each flag's part of the world (Africa, the Americas, Asia,
# Europe, Oceania), for strings of flags made from "a region". From Unicode CLDR's territory
# containment (common/supplemental/supplementalData.xml: the UN M49 groups), the same release as
# the countries' names (tools\fetch-country-names.ps1). A flag's code is climbed through its
# groups (ignoring the groupings CLDR marks grouping="true" or deprecated: the EU, the UN, the
# euro area) to one of the five; a subdivision (gb-eng) takes its country's; what is in none
# (eu, un) is "International".
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\fetch-country-regions.ps1 [-Tag release-49] [-Source <supplementalData.xml>]
param(
    [string]$Tag = "release-49",
    [string]$Source = ""
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$countriesFile = Join-Path $root "RealFlag\Flags\FlagCountries.cs"
$out = Join-Path $root "RealFlag\Flags\FlagRegions.cs"

if ($Source -eq "") {
    $Source = Join-Path ([IO.Path]::GetTempPath()) ("cldr-supplemental-" + [guid]::NewGuid().ToString("N") + ".xml")
    $url = "https://raw.githubusercontent.com/unicode-org/cldr/$Tag/common/supplemental/supplementalData.xml"
    Write-Host "downloading $url"
    Invoke-WebRequest -UseBasicParsing -Uri $url -OutFile $Source
}

[xml]$xml = Get-Content -Raw -Encoding UTF8 $Source

# Child -> its parents, from the groups that are real containment.
$parents = @{}
foreach ($g in $xml.supplementalData.territoryContainment.group) {
    if ($g.grouping -eq "true" -or $g.status -eq "deprecated") { continue }
    foreach ($child in ($g.contains -split '\s+')) {
        if ($child -eq "") { continue }
        if (-not $parents.ContainsKey($child)) { $parents[$child] = New-Object System.Collections.ArrayList }
        [void]$parents[$child].Add($g.type)
    }
}

# The five parts of the world (UN M49), in the order RealFlag numbers them. PERMANENT values.
$regions = [ordered]@{ "002" = 0; "019" = 1; "142" = 2; "150" = 3; "009" = 4 }
$international = 5

function RegionOf([string]$code) {
    $seen = @{}
    $queue = New-Object System.Collections.Queue
    $queue.Enqueue($code)
    while ($queue.Count -gt 0) {
        $c = $queue.Dequeue()
        if ($regions.Contains($c)) { return $regions[$c] }
        if ($seen.ContainsKey($c)) { continue }
        $seen[$c] = $true
        if ($parents.ContainsKey($c)) { foreach ($p in $parents[$c]) { $queue.Enqueue($p) } }
    }
    return $international
}

# The flags' codes, from the generated table.
$codes = @()
foreach ($line in Get-Content -Encoding UTF8 $countriesFile) {
    if ($line -match 'new FlagCountry\("([a-z\-]+)"') { $codes += $Matches[1] }
}
if ($codes.Count -lt 200) { throw "only $($codes.Count) codes read from $countriesFile" }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// GENERATED by tools\fetch-country-regions.ps1 from Unicode CLDR $Tag (supplementalData.xml's")
[void]$sb.AppendLine("// territory containment, the UN M49 groups; Unicode License v3). Do not edit: run the script again.")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("namespace RealFlag.Flags")
[void]$sb.AppendLine("{")
[void]$sb.AppendLine("    public static partial class FlagRegions")
[void]$sb.AppendLine("    {")
[void]$sb.AppendLine("        /// <summary>Each flag's code and its part of the world (a <see cref=""FlagRegions""/> value).</summary>")
[void]$sb.AppendLine("        private static readonly string[] Codes =")
[void]$sb.AppendLine("        {")
$counts = @(0, 0, 0, 0, 0, 0)
$values = @()
foreach ($code in $codes) {
    $country = ($code -split '-')[0].ToUpperInvariant()
    $r = RegionOf $country
    $counts[$r]++
    $values += $r
    [void]$sb.AppendLine("            ""$code"",")
}
[void]$sb.AppendLine("        };")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("        private static readonly byte[] RegionOfCode =")
[void]$sb.AppendLine("        {")
for ($i = 0; $i -lt $values.Count; $i += 32) {
    $chunk = $values[$i..([Math]::Min($i + 31, $values.Count - 1))] -join ", "
    [void]$sb.AppendLine("            $chunk,")
}
[void]$sb.AppendLine("        };")
[void]$sb.AppendLine("    }")
[void]$sb.AppendLine("}")

$utf8 = New-Object System.Text.UTF8Encoding($true)
[IO.File]::WriteAllText($out, $sb.ToString(), $utf8)
Write-Host ("wrote {0}: {1} flags -- Africa {2}, Americas {3}, Asia {4}, Europe {5}, Oceania {6}, international {7}" -f $out, $codes.Count, $counts[0], $counts[1], $counts[2], $counts[3], $counts[4], $counts[5])
